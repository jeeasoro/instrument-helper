const DICTS = { en, de };

let current = detectInitialLang();

function detectInitialLang() {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored && DICTS[stored]) return stored;
  return (navigator.language || 'en').toLowerCase().startsWith('de') ? 'de' : 'en';
}

export function getLang() {
  return current;
}

export function setLang(lang) {
  if (!DICTS[lang]) return;
  current = lang;
  localStorage.setItem(STORAGE_KEY, lang);
  document.documentElement.lang = lang;
  applyTranslations();
  window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
}

/**
 * Look up a key, filling {placeholders} from `params`.
 *
 * Resolution order is instrument-specific first, then plain, then English —
 * each of those in the current language before falling back. A guitar-only
 * string needs no suffix; a string that differs on a piano gets one.
 */
export function t(key, params) {
  const variant = `${key}@${getInstrument()}`;
  const dict = DICTS[current];
  const value = dict[variant] ?? en[variant] ?? dict[key] ?? en[key] ?? key;
  if (!params) return value;
  return value.replace(/\{(\w+)\}/g, (m, name) =>
    (params[name] !== undefined ? params[name] : m));
}

/** Apply translations to every tagged element under `root`. */
export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
}

/** Wire up the language picker present on every page. */
export function initLanguageSwitch() {
  document.documentElement.lang = current;
  const select = document.getElementById('lang');
  if (select) {
    select.value = current;
    select.addEventListener('change', () => setLang(select.value));
  }
  applyTranslations();
}

